function invoiceRow(
  label: string,
  value: string,
  opts: { strongLabel?: boolean; strongValue?: boolean; huge?: boolean } = {}
): string {
  const labelHtml = opts.strongLabel ? `<strong>${escapeHtml(label)}</strong>` : escapeHtml(label)
  const valueClass = opts.strongValue ? "value strong" : "value"
  const valueHtml = opts.huge
    ? `<span class="appt-no">${escapeHtml(value)}</span>`
    : escapeHtml(value)
  return `<tr>
    <td class="label">${labelHtml}</td>
    <td class="colon">:</td>
    <td class="${valueClass}">${valueHtml}</td>
  </tr>`
}

/** Suffix appended on save: ` - Ref Bill No. : ${paidReceipt.receiptNoString}`. Print shows the typed remark only. */
const STORED_REF_BILL_SUFFIX = " - Ref Bill No. : "

function userRefundRemarkForPrint(storedReason: string): string {
  const idx = storedReason.lastIndexOf(STORED_REF_BILL_SUFFIX)
  if (idx === -1) return storedReason
  return storedReason.slice(0, idx).trim()
}

